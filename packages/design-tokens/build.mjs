// Generates platform token files from tokens.json. Run: node packages/design-tokens/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(fs.readFileSync(path.join(here, "tokens.json"), "utf8"));
const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const decls = (obj, prefix = "color") => Object.entries(obj).map(([k, v]) => `  --${prefix}-${kebab(k)}: ${v};`).join("\n");
const px = (obj, prefix) => Object.entries(obj).map(([k, v]) => `  --${prefix}-${kebab(k)}: ${v}px;`).join("\n");

const css = `/* GENERATED by packages/design-tokens/build.mjs — do not edit. */
:root {
  color-scheme: light dark;
${decls(t.color.light)}
${px(t.spacing, "space")}
${px(t.radius, "radius")}
${px(t.fontSize, "text")}
  --touch-target: ${t.touchTarget}px;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decls(t.color.dark).replace(/^ {2}/gm, "    ")}
  }
}
:root[data-theme="dark"] {
${decls(t.color.dark)}
}
`;
fs.writeFileSync(path.resolve(here, "../../apps/web/src/app/tokens.css"), css);

const dart = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const camel = (s) => s;
const colorClass = (name, c) => `  static const ${name} = BfColors(\n${Object.entries(c).map(([k, v]) => `    ${camel(k)}: ${dart(v)},`).join("\n")}\n  );`;
const dartSrc = `// GENERATED by packages/design-tokens/build.mjs — do not edit.
import 'package:flutter/painting.dart';

class BfColors {
  const BfColors({
${Object.keys(t.color.light).map((k) => `    required this.${k},`).join("\n")}
  });
${Object.keys(t.color.light).map((k) => `  final Color ${k};`).join("\n")}
}

class BfTokens {
  BfTokens._();
${colorClass("light", t.color.light)}
${colorClass("dark", t.color.dark)}
${Object.entries(t.spacing).map(([k, v]) => `  static const double space${k[0].toUpperCase() + k.slice(1)} = ${v};`).join("\n")}
${Object.entries(t.radius).map(([k, v]) => `  static const double radius${k[0].toUpperCase() + k.slice(1)} = ${v};`).join("\n")}
${Object.entries(t.fontSize).map(([k, v]) => `  static const double text${k[0].toUpperCase() + k.slice(1)} = ${v};`).join("\n")}
  static const double touchTarget = ${t.touchTarget};
}
`;
const dartDir = path.resolve(here, "../../mobile_packages/design_system/lib/src");
fs.mkdirSync(dartDir, { recursive: true });
fs.writeFileSync(path.join(dartDir, "tokens.g.dart"), dartSrc);
console.log("tokens generated");
